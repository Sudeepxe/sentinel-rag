"""Formal failure taxonomy (spec section 11).

FailureType values are grouped into FailureCategory buckets. Every
diagnosis produced by sentinel.diagnosis must anchor to one of these.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, Field


class FailureCategory(StrEnum):
    RETRIEVAL_FAILURE = "RETRIEVAL_FAILURE"
    CONTEXT_FAILURE = "CONTEXT_FAILURE"
    GENERATION_FAILURE = "GENERATION_FAILURE"
    CITATION_FAILURE = "CITATION_FAILURE"
    REFUSAL_FAILURE = "REFUSAL_FAILURE"
    SECURITY_FAILURE = "SECURITY_FAILURE"
    SYSTEM_FAILURE = "SYSTEM_FAILURE"


class FailureType(StrEnum):
    # RETRIEVAL_FAILURE
    MISSING_RELEVANT_CHUNK = "MISSING_RELEVANT_CHUNK"
    WRONG_RANKING = "WRONG_RANKING"
    SEMANTIC_MISMATCH = "SEMANTIC_MISMATCH"
    QUERY_FORMULATION_FAILURE = "QUERY_FORMULATION_FAILURE"
    METADATA_FILTERING_FAILURE = "METADATA_FILTERING_FAILURE"

    # CONTEXT_FAILURE
    EVIDENCE_OVERLOAD = "EVIDENCE_OVERLOAD"
    CONFLICTING_EVIDENCE = "CONFLICTING_EVIDENCE"
    IRRELEVANT_CONTEXT = "IRRELEVANT_CONTEXT"
    DUPLICATED_EVIDENCE = "DUPLICATED_EVIDENCE"

    # GENERATION_FAILURE
    HALLUCINATION = "HALLUCINATION"
    UNSUPPORTED_CLAIM = "UNSUPPORTED_CLAIM"
    INCOMPLETE_ANSWER = "INCOMPLETE_ANSWER"
    INSTRUCTION_FOLLOWING_FAILURE = "INSTRUCTION_FOLLOWING_FAILURE"

    # CITATION_FAILURE
    MISSING_CITATION = "MISSING_CITATION"
    INCORRECT_CITATION = "INCORRECT_CITATION"
    PARTIAL_CITATION = "PARTIAL_CITATION"
    CITATION_MISMATCH = "CITATION_MISMATCH"

    # REFUSAL_FAILURE
    FALSE_REFUSAL = "FALSE_REFUSAL"
    UNSAFE_ANSWER = "UNSAFE_ANSWER"
    REFUSAL_WITHOUT_EVIDENCE = "REFUSAL_WITHOUT_EVIDENCE"
    ANSWERED_UNANSWERABLE = "ANSWERED_UNANSWERABLE"

    # SECURITY_FAILURE
    PROMPT_INJECTION = "PROMPT_INJECTION"
    INDIRECT_PROMPT_INJECTION = "INDIRECT_PROMPT_INJECTION"
    TOOL_MANIPULATION = "TOOL_MANIPULATION"
    DATA_EXFILTRATION_ATTEMPT = "DATA_EXFILTRATION_ATTEMPT"

    # SYSTEM_FAILURE
    TIMEOUT = "TIMEOUT"
    PROVIDER_FAILURE = "PROVIDER_FAILURE"
    MALFORMED_RESPONSE = "MALFORMED_RESPONSE"
    RATE_LIMIT = "RATE_LIMIT"
    DEPENDENCY_FAILURE = "DEPENDENCY_FAILURE"


FAILURE_CATEGORY_MAP: dict[FailureType, FailureCategory] = {
    FailureType.MISSING_RELEVANT_CHUNK: FailureCategory.RETRIEVAL_FAILURE,
    FailureType.WRONG_RANKING: FailureCategory.RETRIEVAL_FAILURE,
    FailureType.SEMANTIC_MISMATCH: FailureCategory.RETRIEVAL_FAILURE,
    FailureType.QUERY_FORMULATION_FAILURE: FailureCategory.RETRIEVAL_FAILURE,
    FailureType.METADATA_FILTERING_FAILURE: FailureCategory.RETRIEVAL_FAILURE,
    FailureType.EVIDENCE_OVERLOAD: FailureCategory.CONTEXT_FAILURE,
    FailureType.CONFLICTING_EVIDENCE: FailureCategory.CONTEXT_FAILURE,
    FailureType.IRRELEVANT_CONTEXT: FailureCategory.CONTEXT_FAILURE,
    FailureType.DUPLICATED_EVIDENCE: FailureCategory.CONTEXT_FAILURE,
    FailureType.HALLUCINATION: FailureCategory.GENERATION_FAILURE,
    FailureType.UNSUPPORTED_CLAIM: FailureCategory.GENERATION_FAILURE,
    FailureType.INCOMPLETE_ANSWER: FailureCategory.GENERATION_FAILURE,
    FailureType.INSTRUCTION_FOLLOWING_FAILURE: FailureCategory.GENERATION_FAILURE,
    FailureType.MISSING_CITATION: FailureCategory.CITATION_FAILURE,
    FailureType.INCORRECT_CITATION: FailureCategory.CITATION_FAILURE,
    FailureType.PARTIAL_CITATION: FailureCategory.CITATION_FAILURE,
    FailureType.CITATION_MISMATCH: FailureCategory.CITATION_FAILURE,
    FailureType.FALSE_REFUSAL: FailureCategory.REFUSAL_FAILURE,
    FailureType.UNSAFE_ANSWER: FailureCategory.REFUSAL_FAILURE,
    FailureType.REFUSAL_WITHOUT_EVIDENCE: FailureCategory.REFUSAL_FAILURE,
    FailureType.ANSWERED_UNANSWERABLE: FailureCategory.REFUSAL_FAILURE,
    FailureType.PROMPT_INJECTION: FailureCategory.SECURITY_FAILURE,
    FailureType.INDIRECT_PROMPT_INJECTION: FailureCategory.SECURITY_FAILURE,
    FailureType.TOOL_MANIPULATION: FailureCategory.SECURITY_FAILURE,
    FailureType.DATA_EXFILTRATION_ATTEMPT: FailureCategory.SECURITY_FAILURE,
    FailureType.TIMEOUT: FailureCategory.SYSTEM_FAILURE,
    FailureType.PROVIDER_FAILURE: FailureCategory.SYSTEM_FAILURE,
    FailureType.MALFORMED_RESPONSE: FailureCategory.SYSTEM_FAILURE,
    FailureType.RATE_LIMIT: FailureCategory.SYSTEM_FAILURE,
    FailureType.DEPENDENCY_FAILURE: FailureCategory.SYSTEM_FAILURE,
}


class FailureRecord(BaseModel):
    case_id: str
    primary: FailureType
    secondary: list[FailureType] = Field(default_factory=list)
    evidence: dict[str, object] = Field(default_factory=dict)
    confidence: float = Field(ge=0.0, le=1.0)
    likely_cause: str
    explanation: str = ""

    @property
    def primary_category(self) -> FailureCategory:
        return FAILURE_CATEGORY_MAP[self.primary]
